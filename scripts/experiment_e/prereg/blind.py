#!/usr/bin/env python3
"""Experiment E blinding and randomisation tools.

What this does and does NOT do
  * schedule   Reproducible randomised dwell order per fc, seeded from public text (e.g. the freeze commit hash), so
               the order cannot be chosen after seeing data. The evaluator checks the recorded data against it.
  * commit     A second operator draws the Stage 4 secret centre frequencies from os.urandom and publishes only a
               SHA-256 commitment. The secret file stays with that operator.
  * reveal     Verifies the commitment, checks the analyst's estimates were hashed first, and writes truths.
  Blinding is PROCEDURAL. Software cannot stop the second operator opening their own file or the analyst reading
  the secret from disk; the commitment makes any later change to the secret detectable, and the estimate hash makes
  any later change to the analyst's estimates detectable. Stage 1/2 analysis cannot be blind to control roles (the
  C3/C4 rules differ by role); there the protection is the frozen rule, the automated evaluator, and the
  randomised order.

Blinding modes for Stage 4 (recorded in the commitment and the reveal record; the evaluator awards the top verdict,
"tuned frequency inferred under blinded conditions", only when the mode's checks pass):
  human_second_operator        a different person draws the secret, tunes the DUT and holds the secret; the record names
                               operator and analyst, which must differ.
  os_account_separation        the secret and the trial driver belong to a separate OS account that the analyst account
                               cannot read; the reveal checks the secret file and the estimates file have different owners.
                               Needs a second account on the DUT host (sudo to create).
  self_with_external_commitment  one person does everything, but the commitment hash is published somewhere outside their
                               control (a public commit, a message to a third party) BEFORE the first trial, and the
                               secret is generated by a script and not opened until the estimates are hashed. Weakest:
                               it makes changes detectable, not peeking.
  (no mode)                    Stage 4 can still be run and reported, but cannot support the blinded verdict (rung 5).

usage
  blind.py schedule --seed-text TEXT [--fc 3e6,7.5e6,12e6] [--sweep 200000,14000000,100000] [--ref-every 10] --out sched.json
  blind.py commit  --mode MODE --n 20 [--lo 2e6 --hi 12e6 --gran 10000] --secret secret.json --commitment commitment.json
  blind.py reveal  --secret secret.json --commitment commitment.json --estimates est.json --estimates-sha256 H --truths truths.json
                   --record reveal_record.json [--operator NAME --analyst NAME] [--published-to WHERE]
"""
import sys, os, json, hashlib, secrets, argparse, time
import numpy as np


def canonical(o): return json.dumps(o, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
def sha(s): return hashlib.sha256(s.encode()).hexdigest()
def file_sha(p): return hashlib.sha256(open(p, "rb").read()).hexdigest()


def seed_from_text(t): return int(hashlib.sha256(t.encode()).hexdigest()[:15], 16)


def make_schedule(seed_text, fcs, sweep, ref_every=10):
    f_all = np.arange(sweep[0], sweep[1] + 1, sweep[2], dtype=float)
    rng = np.random.default_rng(seed_from_text(seed_text)); sched = []
    for fc in fcs:
        order = rng.permutation(len(f_all)); plan = [("ref", fc)]
        for i, k in enumerate(order):
            plan.append(("probe", float(f_all[k])))
            if (i + 1) % ref_every == 0: plan.append(("ref", fc))
        plan.append(("ref", fc))
        for seq, (kind, f) in enumerate(plan): sched.append(dict(fc_hz=float(fc), seq=seq, is_ref=1 if kind == "ref" else 0, f_hz=float(f)))
    return dict(seed_text=seed_text, fcs=list(map(float, fcs)), sweep=list(sweep), ref_every=ref_every, dwells=sched,
                schedule_sha256=sha(canonical(sched)))


def schedule_matches(sweeps, sched):
    """True iff the recorded (fc, seq, is_ref, f) rows are exactly the preregistered schedule (probe-off rows carry fc as f)."""
    rec = sorted((float(a), int(b), int(c), float(d)) for a, b, c, d in zip(sweeps["fc_hz"], sweeps["seq"], sweeps["is_ref"], sweeps["f_hz"]))
    exp = sorted((d["fc_hz"], d["seq"], d["is_ref"], d["f_hz"]) for d in sched["dwells"])
    return rec == exp and sha(canonical(sched["dwells"])) == sched["schedule_sha256"]


MODES = ("human_second_operator", "os_account_separation", "self_with_external_commitment")


def commit(n, lo, hi, gran, mode="human_second_operator"):
    if mode not in MODES: raise ValueError(f"mode must be one of {MODES}")
    rng = np.random.default_rng(int.from_bytes(secrets.token_bytes(8), "big"))
    trials = {f"t{j:02d}": float(rng.integers(int(lo // gran), int(hi // gran) + 1) * gran) for j in range(n)}
    secret = dict(trials=trials, nonce=secrets.token_hex(16), range_hz=[lo, hi], granularity_hz=gran)
    commitment = dict(commitment_sha256=sha(canonical(secret)), n=n, mode=mode, created_utc=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()))
    return secret, commitment


def reveal(secret, commitment, estimates_path, estimates_sha256, secret_path=None, operator=None, analyst=None, published_to=None):
    """Verify the commitment and the mode's attestations. Returns (truths, record)."""
    if sha(canonical(secret)) != commitment["commitment_sha256"]: raise ValueError("secret does not match the published commitment")
    if file_sha(estimates_path) != estimates_sha256: raise ValueError("estimates file differs from the hash recorded before the reveal")
    est = json.load(open(estimates_path))
    if set(est) != set(secret["trials"]): raise ValueError("estimates and secret cover different trials")
    mode = commitment.get("mode"); att = {}
    if mode == "human_second_operator":
        if not operator or not analyst: raise ValueError("human_second_operator needs --operator and --analyst")
        if operator.strip().lower() == analyst.strip().lower(): raise ValueError("operator and analyst are the same person: that is not a second operator")
        att = dict(operator=operator, analyst=analyst)
    elif mode == "os_account_separation":
        if not secret_path: raise ValueError("os_account_separation needs the secret file path to check its owner")
        so, eo = os.stat(secret_path).st_uid, os.stat(estimates_path).st_uid
        if so == eo: raise ValueError(f"the secret and the estimates belong to the same OS user (uid {so}): no account separation")
        att = dict(secret_uid=so, estimates_uid=eo)
    elif mode == "self_with_external_commitment":
        if not published_to or not published_to.strip(): raise ValueError("self_with_external_commitment needs --published-to (where the hash was published before the first trial)")
        att = dict(published_to=published_to)
    else:
        raise ValueError(f"commitment has no valid blinding mode ({mode!r})")
    record = dict(mode=mode, commitment_sha256=commitment["commitment_sha256"], estimates_sha256=estimates_sha256, n_trials=len(est),
                  attestation=att, verified_utc=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()))
    return secret["trials"], record


def verify_record(record, estimates_path, truths_path, commitment=None):
    """True iff the record matches the files the evaluator was given (and the published commitment, when supplied)."""
    ok = record.get("mode") in MODES and record.get("estimates_sha256") == file_sha(estimates_path)
    if ok and record.get("truths_sha256") != file_sha(truths_path): ok = False
    if ok and commitment is not None: ok = commitment.get("commitment_sha256") == record.get("commitment_sha256") and commitment.get("mode") == record.get("mode")
    return bool(ok)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["schedule", "commit", "reveal"])
    ap.add_argument("--seed-text"); ap.add_argument("--fc", default="3e6,7.5e6,12e6"); ap.add_argument("--sweep", default="200000,14000000,100000")
    ap.add_argument("--ref-every", type=int, default=10); ap.add_argument("--out")
    ap.add_argument("--n", type=int, default=20); ap.add_argument("--lo", type=float, default=2e6); ap.add_argument("--hi", type=float, default=12e6)
    ap.add_argument("--gran", type=float, default=10000); ap.add_argument("--secret"); ap.add_argument("--commitment")
    ap.add_argument("--estimates"); ap.add_argument("--estimates-sha256"); ap.add_argument("--truths")
    ap.add_argument("--mode", default="human_second_operator", choices=MODES); ap.add_argument("--record")
    ap.add_argument("--operator"); ap.add_argument("--analyst"); ap.add_argument("--published-to")
    a = ap.parse_args()
    if a.cmd == "schedule":
        s = make_schedule(a.seed_text, [float(x) for x in a.fc.split(",")], [float(x) for x in a.sweep.split(",")], a.ref_every)
        json.dump(s, open(a.out, "w")); print("schedule_sha256", s["schedule_sha256"])
    elif a.cmd == "commit":
        sec, com = commit(a.n, a.lo, a.hi, a.gran, a.mode)
        fd = os.open(a.secret, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600); os.write(fd, json.dumps(sec).encode()); os.close(fd)
        json.dump(com, open(a.commitment, "w")); print("PUBLISH THIS:", com["commitment_sha256"])
    else:
        t, rec = reveal(json.load(open(a.secret)), json.load(open(a.commitment)), a.estimates, a.estimates_sha256, a.secret, a.operator, a.analyst, a.published_to)
        json.dump(t, open(a.truths, "w")); rec["truths_sha256"] = file_sha(a.truths); json.dump(rec, open(a.record, "w"), indent=1)
        print("commitment and", rec["mode"], "attestation verified; truths ->", a.truths, "; record ->", a.record)


if __name__ == "__main__":
    main()
